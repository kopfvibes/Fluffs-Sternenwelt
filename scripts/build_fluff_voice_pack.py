#!/usr/bin/env python3
"""Create OFFLINE Fluff narration using the owner's existing HeyGen voice.

Dry-run by default. Only --generate consumes paid HeyGen API characters.
Never include children's names, task notes, or personally identifying text.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "voice/fluff_narration_lines.json"
BASE = ROOT / "assets/audio/narration"
DART = ROOT / "lib/services/offline_fluff_narration.dart"
MANIFEST = ROOT / "pro-voice-manifest.json"
API = "https://api.heygen.com/v3/voices/speech"

def key(text: str) -> str:
    return re.sub(r"[.!?…]+$", "", re.sub(r"\s+", " ", text.strip().lower()))

def dart_string(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"

def write_mapping(mapping: dict[str, str]) -> None:
    data = [
        "// GENERATED by scripts/build_fluff_voice_pack.py. Do not edit manually.",
        "// All files below must use the same HeyGen voice as pro-voice-manifest.json.",
        "const offlineFluffNarrationClips = <String, String>{",
    ]
    for phrase, asset in sorted(mapping.items()):
        data.append(f"  {dart_string(phrase)}: {dart_string(asset)},")
    data.append("};")
    DART.write_text("\n".join(data) + "\n", encoding="utf-8")

def create_audio(text: str, voice_id: str, secret: str, dest: Path) -> None:
    payload = json.dumps({
        "voice_id": voice_id,
        "text": text,
        "language": "de",
        "speed": 0.95,
        "engine": "elevenlabs",
        "input_type": "text",
    }).encode("utf-8")
    request = urllib.request.Request(
        API, data=payload,
        headers={"X-Api-Key": secret, "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        result = json.load(response)
    audio_url = (result.get("data") or {}).get("audio_url")
    if not audio_url or not audio_url.startswith("https://"):
        raise RuntimeError("HeyGen did not return a valid audio URL.")
    with tempfile.TemporaryDirectory(prefix="fluff-voice-") as tmp:
        source = Path(tmp) / "speech"
        urllib.request.urlretrieve(audio_url, source)
        if source.stat().st_size < 256:
            raise RuntimeError("Empty or invalid speech audio.")
        # Match the original bundled Fluff MP3 playback format.
        subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i",
            str(source), "-ac", "1", "-ar", "24000", "-b:a", "64k",
            str(dest)], check=True)

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true",
        help="Explicitly request PAID HeyGen speech generation.")
    parser.add_argument("--limit", type=int, default=None,
        help="Optional maximum number of new clips to generate.")
    args = parser.parse_args()
    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be positive")
    voice_id = json.loads(MANIFEST.read_text(encoding="utf-8"))["voice_id"]
    originals = json.loads(MANIFEST.read_text(encoding="utf-8"))["clips"]
    already = {entry["key"] for entry in originals}
    entries = json.loads(CATALOG.read_text(encoding="utf-8"))["lines"]
    existing: dict[str, str] = {}
    # Keep existing generated clips even when resuming after a partial run.
    if DART.exists():
        for phrase, asset in re.findall(r"^\s*'((?:\\.|[^'])*)': '([^']+)',\s*$",
                                         DART.read_text(encoding="utf-8"), flags=re.M):
            if (ROOT / "assets" / asset).is_file():
                existing[phrase] = asset
    remaining = [(key(text), text) for text in entries
                 if key(text) not in already and key(text) not in existing]
    unique = list(dict(((phrase, phrase_text) for phrase, phrase_text in remaining)).values())
    print(f"Existing original recordings: {len(already)}")
    print(f"Existing new narration recordings: {len(existing)}")
    print(f"Additional fixed narrations needed: {len(unique)}")
    print(f"Characters for remaining narration: {sum(map(len, unique))}")
    if not args.generate:
        print("Dry run only. Use --generate with HEYGEN_API_KEY for paid synthesis.")
        return
    secret = os.getenv("HEYGEN_API_KEY")
    if not secret:
        raise SystemExit("HEYGEN_API_KEY must be set in the environment; never place it in source code.")
    BASE.mkdir(parents=True, exist_ok=True)
    selected = unique if args.limit is None else unique[:args.limit]
    for i, text in enumerate(selected, 1):
        phrase = key(text)
        filename = hashlib.sha256(phrase.encode("utf-8")).hexdigest()[:24] + ".mp3"
        target = BASE / filename
        print(f"Generating {i}/{len(selected)}: {phrase[:75]}")
        # Atomic asset writes; an interrupted request cannot corrupt a finished file.
        staging = BASE / (filename + ".tmp.mp3")
        try:
            create_audio(text, voice_id, secret, staging)
            staging.replace(target)
        finally:
            staging.unlink(missing_ok=True)
        existing[phrase] = "audio/narration/" + filename
        write_mapping(existing)
    print(f"Completed {len(selected)} new Fluff clips. Commit the generated media and Dart mapping.")

if __name__ == "__main__":
    main()
